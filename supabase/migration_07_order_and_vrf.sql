-- 4) пересоздать представления (c.* / e.* фиксируются при создании — без этого ord не виден)
drop view if exists cable_progress;
create view cable_progress with (security_invoker = true) as
select c.*,
  coalesce((select sum(l.qty) from cable_logs l where l.cable_id = c.id), 0)::numeric as installed,
  (select l.completed   from cable_logs l where l.cable_id = c.id order by l.date desc, l.id desc limit 1) as last_completed,
  (select l.stop_reason from cable_logs l where l.cable_id = c.id order by l.date desc, l.id desc limit 1) as last_stop_reason
from cables c;
grant select on cable_progress to authenticated;

drop view if exists equipment_progress;
create view equipment_progress with (security_invoker = true) as
select e.*,
  coalesce((select sum(l.qty) from equipment_logs l where l.equipment_id = e.id), 0)::numeric as installed,
  (select l.date from equipment_logs l where l.equipment_id = e.id order by l.date desc, l.id desc limit 1) as last_date,
  (select p.full_name from equipment_logs l join profiles p on p.id = l.user_id
     where l.equipment_id = e.id order by l.date desc, l.id desc limit 1) as last_user_name
from equipment e;
grant select on equipment_progress to authenticated;

-- 5) проверка: без_порядка должно быть 0
select section, count(*) as кабелей, count(*) filter (where ord is null) as без_порядка, sum(length) as метров
from cables group by section order by section;
